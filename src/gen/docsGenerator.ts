// kintone アプリ管理ドキュメント生成（純粋関数群）
import type { Customization } from '../models.js';
import type { SchemaMeta } from './digestGenerator.js';

export type AppSchemaData = {
    appName: string;
    meta: SchemaMeta;
    fields: Record<string, any>;
    layout: any[];
    views: Record<string, any>;
    devRevision?: string;
    prodRevision?: string;
};

function toMermaidId(name: string): string {
    return 'n_' + name.replace(/[^a-zA-Z0-9]/g, '_');
}

function escapeMdCell(v: string): string {
    return v.replace(/\|/g, '\\|').replace(/\n/g, ' ').replace(/\r/g, '');
}

function appUrl(app: { baseUrl: string; appId: string; guestSpaceId: string }): string {
    if (app.guestSpaceId) {
        return `${app.baseUrl}/k/guest/${app.guestSpaceId}/${app.appId}`;
    }
    return `${app.baseUrl}/k/${app.appId}`;
}

/**
 * docs/schema/README.md の内容を文字列で生成する純粋関数。
 * アプリ名順にソートした管理アプリ一覧テーブル（dev/prod appId リンク、profile名、
 * フィールド数、dev revision、prod revision、digestリンク）を含む。
 * Mermaid 依存グラフとアプリごとのサマリも生成する。
 * ファイル書き込みや API 呼び出しは行わない。
 * devRevision/prodRevision は AppSchemaData フィールドから取得する（省略可）。
 * @param apps           - アプリスキーマデータの配列（devRevision/prodRevision を含む場合あり）
 * @param customizations - appId/profile/URL 解決用のカスタマイズレジストリ
 */
export function generateReadme(
    apps: AppSchemaData[],
    customizations: Record<string, Customization>,
): string {
    const sorted = [...apps].sort((a, b) => a.appName.localeCompare(b.appName));
    const lines: string[] = [
        '# kintone アプリ管理一覧',
        '',
        '> generated by `erakis schema docs`',
        '> 再生成: `npx erakis schema docs`',
        '',
        '## 管理アプリ一覧',
        '',
        '| アプリ名 | dev appId | dev profile | prod appId | prod profile | フィールド数 | dev rev | prod rev | ダイジェスト |',
        '|---|---|---|---|---|---|---|---|---|',
    ];

    for (const app of sorted) {
        const fieldCount = Object.keys(app.fields).length;
        const digestLink = `[digest](./${app.appName}.digest.md)`;
        const custom = customizations[app.appName];

        const devAppId = custom?.development?.appId ?? '';
        const devProfile = custom?.development?.profileName ?? '';
        const devUrl = custom?.development ? appUrl(custom.development) : '';
        const prodAppId = custom?.production?.appId ?? '';
        const prodProfile = custom?.production?.profileName ?? '';
        const prodUrl = custom?.production ? appUrl(custom.production) : '';

        const devCell = devAppId ? `[${devAppId}](${devUrl})` : '';
        const prodCell = prodAppId ? `[${prodAppId}](${prodUrl})` : '';

        const devRev = app.devRevision ?? '';
        const prodRev = app.prodRevision ?? '';
        lines.push(`| ${escapeMdCell(app.appName)} | ${devCell} | ${devProfile} | ${prodCell} | ${prodProfile} | ${fieldCount} | ${devRev} | ${prodRev} | ${digestLink} |`);
    }
    lines.push('');

    // アプリ関連図 (mermaid)
    const mermaid = buildMermaidGraph(sorted, customizations);
    if (mermaid) {
        lines.push('## アプリ関連図');
        lines.push('');
        lines.push('```mermaid');
        lines.push(mermaid);
        lines.push('```');
        lines.push('');
    }

    // アプリごとのサマリ
    lines.push('## アプリサマリ');
    lines.push('');
    for (const app of sorted) {
        lines.push(buildAppSummary(app));
    }

    return lines.join('\n');
}

/**
 * lookup / REFERENCE_TABLE の依存関係を mermaid 図にする純粋関数
 */
export function buildMermaidGraph(
    apps: AppSchemaData[],
    customizations: Record<string, Customization>,
): string {
    // appId → appName の逆引きマップ（erakis管理下）
    const appIdToName = new Map<string, string>();
    for (const app of apps) {
        appIdToName.set(app.meta.appId, app.appName);
        const custom = customizations[app.appName];
        if (custom?.production) appIdToName.set(custom.production.appId, app.appName);
    }

    const edges: string[] = [];
    const externalIds = new Set<string>();

    for (const app of apps) {
        const fromId = toMermaidId(app.appName);
        for (const field of Object.values(app.fields)) {
            const f = field as any;
            // lookup
            if (f.lookup?.relatedApp?.app) {
                const relAppId = String(f.lookup.relatedApp.app);
                const relName = appIdToName.get(relAppId);
                if (relName) {
                    edges.push(`  ${fromId} -->|lookup| ${toMermaidId(relName)}`);
                } else {
                    const extId = `ext_${relAppId}`;
                    externalIds.add(`  ${extId}["app ${relAppId} (外部)"]`);
                    edges.push(`  ${fromId} -->|lookup| ${extId}`);
                }
            }
            // REFERENCE_TABLE
            if (f.type === 'REFERENCE_TABLE' && f.referenceTable?.relatedApp?.app) {
                const relAppId = String(f.referenceTable.relatedApp.app);
                const relName = appIdToName.get(relAppId);
                if (relName) {
                    edges.push(`  ${fromId} -.->|ref| ${toMermaidId(relName)}`);
                } else {
                    const extId = `ext_${relAppId}`;
                    externalIds.add(`  ${extId}["app ${relAppId} (外部)"]`);
                    edges.push(`  ${fromId} -.->|ref| ${extId}`);
                }
            }
        }
    }

    if (edges.length === 0 && externalIds.size === 0) return '';

    const nodeLines = apps.map(a => `  ${toMermaidId(a.appName)}["${a.appName}\\n(app:${a.meta.appId})"]`);
    return ['graph LR', ...nodeLines, ...[...externalIds], ...edges].join('\n');
}

/**
 * アプリ1件のサマリ（型別件数・SUBTABLE一覧・Views一覧）を Markdown で生成する純粋関数
 */
export function buildAppSummary(app: AppSchemaData): string {
    const lines: string[] = [`### ${escapeMdCell(app.appName)}`, ''];

    // フィールド型別件数
    const typeCounts: Record<string, number> = {};
    for (const field of Object.values(app.fields)) {
        const type = (field as any).type ?? 'UNKNOWN';
        typeCounts[type] = (typeCounts[type] ?? 0) + 1;
    }
    lines.push('**フィールド型別件数**', '');
    lines.push('| 型 | 件数 |', '|---|---|');
    for (const [type, count] of Object.entries(typeCounts).sort(([a], [b]) => a.localeCompare(b))) {
        lines.push(`| ${type} | ${count} |`);
    }
    lines.push('');

    // SUBTABLE 一覧
    const subtables = Object.entries(app.fields)
        .filter(([, f]) => (f as any).type === 'SUBTABLE')
        .map(([code, f]) => ({ code, childCount: Object.keys((f as any).fields ?? {}).length }));
    if (subtables.length > 0) {
        lines.push('**SUBTABLE 一覧**', '');
        for (const st of subtables) {
            lines.push(`- \`${st.code}\` (子フィールド: ${st.childCount}件)`);
        }
        lines.push('');
    }

    // Views 一覧
    const viewEntries = Object.entries(app.views).sort(([a], [b]) => a.localeCompare(b));
    if (viewEntries.length > 0) {
        lines.push('**Views 一覧**', '');
        lines.push('| ビュー名 | 種類 |', '|---|---|');
        for (const [name, view] of viewEntries) {
            lines.push(`| ${escapeMdCell(name)} | ${(view as any).type ?? ''} |`);
        }
        lines.push('');
    }

    return lines.join('\n');
}
